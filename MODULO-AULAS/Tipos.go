package main

import (
	"fmt"
)

func main() {
	//tipos:
	//boll(true,false)
	fmt.Printf("Type:%T-Valure:%v\n", true, true)

	//string-sequencia bytes
	fmt.Printf("Type:%T-Valure:%v\n", "setph", "setph")
	fmt.Printf("Type:%T-Valure:%v\n", "1", "1")

	//int
	fmt.Printf("Type:%T-Valure:%v\n", 1, 1)

	//float(float64,float32)decimal
	fmt.Printf("Type:%T-Valure:%v\n", 1.233, 1.233)
}
